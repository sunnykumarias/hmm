import threading
_claim_lock = threading.Lock()

def claim_one():
    """Claim one account: Redis queue first (fleet), accounts.txt fallback (local)."""
    import json, time, os
    with _claim_lock:
        try:
            # ── REDIS CLAIM (fleet) ──
            try:
                rc = _r()
                raw = rc.brpoplpush("queue:pending", PROC_KEY, timeout=5)
                if raw:
                    item = json.loads(raw)
                    # done_qids guard (reclaim-race protection)
                    if rc.sismember("queue:done_qids", item.get("qid", "")):
                        rc.lrem(PROC_KEY, 1, raw)
                        return None
                    return (raw, item)
            except Exception as re:
                # Redis down → "DOWN" signal (worker_loop handles retry)
                if "Connection" in type(re).__name__ or "Timeout" in str(type(re)):
                    return "DOWN"
                pass
            # ── NO LOCAL FALLBACK — Redis only (user order) ──
            time.sleep(5)
            return None
            with open("accounts.txt", "r") as f:
                lines = f.readlines()
            
            first_line = None
            while lines:
                l = lines.pop(0).strip()
                if l and "|" in l:
                    first_line = l
                    break
                    
            if first_line:
                # Write the remaining lines back to the file
                with open("accounts.txt", "w") as f:
                    f.writelines(lines)
                    
                email, pwd = first_line.split("|", 1)
                item = {"email": email.strip(), "password": pwd.strip(), "qid": 1}
                return (json.dumps(item), item)
        except Exception as e:
            print(f"Error in claim_one: {e}")
            
    time.sleep(5) # wait if queue is empty so we don't spin fast
    return None

