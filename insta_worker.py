# BOOTSTRAP: Auto-install all required packages BEFORE any imports
# This runs first so even a fresh Google Cloud Shell works out of the box.
# ══════════════════════════════════════════════════════════════════════════════
def _bootstrap_install():
    # ── Step 1: Install Python packages ─────────────────────────────────────
    pkgs = {
        "playwright":         "playwright",
        "playwright_stealth": "playwright-stealth",
        "pyotp":              "pyotp",
        "requests":           "requests",
        "redis":              "redis",
    }
    needs_restart = False
    for import_name, pip_name in pkgs.items():
        try:
            __import__(import_name)
        except ImportError:
            print(f"[BOOTSTRAP] Installing Python package: {pip_name}...")
            subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", pip_name])
            needs_restart = True

    # ── Step 2: Install Playwright Chromium browser + system deps ────────────
    try:
        subprocess.run(
            [sys.executable, "-m", "playwright", "install", "chromium"],
            capture_output=True, text=True
        )
        subprocess.run(
            [sys.executable, "-m", "playwright", "install-deps", "chromium"],
            capture_output=True
        )
    except Exception as e:
        print(f"[BOOTSTRAP] playwright install warning: {e}")

    # ── Step 3: Install Tor via apt-get if not present ───────────────────────
    if subprocess.run(["which", "tor"], capture_output=True).returncode != 0:
        print("[BOOTSTRAP] Tor not found. Installing via apt-get...")
        subprocess.run(["sudo", "apt-get", "update", "-y"], check=True)
        subprocess.run(["sudo", "apt-get", "install", "-y", "tor"], check=True)
        print("[BOOTSTRAP] Tor installed successfully.")
    else:
        print("[BOOTSTRAP] Tor already installed.")

    # ── Step 4: Configure torrc with IsolateSOCKSAuth ───────────────────────
    torrc_content = (
        "# Auto-generated by insta_tor_ip_gclud.py\n"
        "SocksPort 9050 IsolateSOCKSAuth\n"
        "DataDirectory /var/lib/tor\n"
        "Log notice stdout\n"
    )
    torrc_path = "/etc/tor/torrc"
    try:
        with open(torrc_path, "w") as f:
            f.write(torrc_content)
        print("[BOOTSTRAP] torrc configured with IsolateSOCKSAuth.")
    except PermissionError:
        proc = subprocess.Popen(
            ["sudo", "tee", torrc_path],
            stdin=subprocess.PIPE, stdout=subprocess.DEVNULL
        )
        proc.communicate(torrc_content.encode())
        print("[BOOTSTRAP] torrc configured (via sudo tee).")

    # ── Step 5: (Re)start Tor service ───────────────────────────────────────
    print("[BOOTSTRAP] Starting Tor service...")
    subprocess.run(["sudo", "service", "tor", "stop"], capture_output=True)
    try:
        subprocess.run(["sudo", "service", "tor", "start"], check=True, capture_output=True)
    except subprocess.CalledProcessError:
        # Some cloud envs need systemctl instead of service
        subprocess.run(["sudo", "systemctl", "restart", "tor"], check=True)

    # ── Step 6: Wait for Tor to be ready ────────────────────────────────────
    import time as _time
    print("[BOOTSTRAP] Waiting for Tor to bootstrap on port 9050...")
    for _ in range(30):
        try:
            import socket as _sock
            s = _sock.create_connection(("127.0.0.1", 9050), timeout=2)
            s.close()
            print("[BOOTSTRAP] Tor is ready!")
            break
        except OSError:
            _time.sleep(2)
    else:
        print("[BOOTSTRAP] WARNING: Tor may not have started. Continuing anyway...")

    # ── Step 7: Restart self if packages were newly installed ────────────────
    if needs_restart:
        print("[BOOTSTRAP] Restarting script with all packages available...")
        os.execv(sys.executable, [sys.executable] + sys.argv)

_bootstrap_install()
