def setup_tor():
    """
    Auto-install and configure Tor on Linux (Google Cloud Shell / Compute Engine).
    Ensures IsolateSOCKSAuth is set so each thread gets a unique IP.
    """
    # ── 1. Install Tor if missing ─────────────────────────────────────────
    if subprocess.run(["which", "tor"], capture_output=True).returncode != 0:
        print(f"{Colors.OKCYAN}[*] Tor not found. Installing via apt-get...{Colors.ENDC}")
        subprocess.run(["sudo", "apt-get", "update", "-y"], check=True)
        subprocess.run(["sudo", "apt-get", "install", "-y", "tor"], check=True)
        print(f"{Colors.OKGREEN}[+] Tor installed successfully.{Colors.ENDC}")
    else:
        print(f"{Colors.OKGREEN}[+] Tor is already installed.{Colors.ENDC}")

    # ── 2. Write torrc to enable IsolateSOCKSAuth ─────────────────────────
    torrc_content = """
# Auto-generated by insta_tor_ip_gclud.py
SocksPort 9050 IsolateSOCKSAuth
DataDirectory /var/lib/tor
Log notice stdout
"""
    torrc_path = "/etc/tor/torrc"
    try:
        with open(torrc_path, "w") as f:
            f.write(torrc_content)
        print(f"{Colors.OKGREEN}[+] torrc configured with IsolateSOCKSAuth.{Colors.ENDC}")
    except PermissionError:
        print(f"{Colors.WARNING}[!] Cannot write torrc directly — trying sudo tee...{Colors.ENDC}")
        proc = subprocess.Popen(
            ["sudo", "tee", torrc_path],
            stdin=subprocess.PIPE, stdout=subprocess.DEVNULL
        )
        proc.communicate(torrc_content.encode())

    # ── 3. Stop any existing Tor, then start fresh ───────────────────────
    print(f"{Colors.OKCYAN}[*] Starting Tor service...{Colors.ENDC}")
    subprocess.run(["sudo", "service", "tor", "stop"],  capture_output=True)
    subprocess.run(["sudo", "service", "tor", "start"], check=True)

    # ── 4. Wait until Tor is ready (bootstrapped) ────────────────────────
    print(f"{Colors.OKCYAN}[*] Waiting for Tor to bootstrap...{Colors.ENDC}")
    import time
    for attempt in range(30):
        try:
            test_sock = socket.create_connection(("127.0.0.1", 9050), timeout=2)
            test_sock.close()
            print(f"{Colors.OKGREEN}[+] Tor is ready on port 9050!{Colors.ENDC}")
            return
        except (ConnectionRefusedError, OSError):
            time.sleep(2)
    print(f"{Colors.FAIL}[!] Tor did not start within 60 seconds. Check: sudo service tor status{Colors.ENDC}")
    sys.exit(1)


def _restart_tor_fresh():
    """Tor service restart karke fresh circuits lo. Auto-renew me use hota hai."""
