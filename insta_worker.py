async def start_local_proxy(tor_port, username, password):
    async def handle_client(reader, writer):
        try:
            version, nmethods = struct.unpack("!BB", await reader.readexactly(2))
            await reader.readexactly(nmethods)
            writer.write(b"\x05\x00")
            await writer.drain()

            req_header = await reader.readexactly(4)
            version, cmd, _, address_type = struct.unpack("!BBBB", req_header)
            
            if address_type == 1:
                addr_data = await reader.readexactly(4)
            elif address_type == 3:
                domain_len = (await reader.readexactly(1))[0]
                addr_data = struct.pack("!B", domain_len) + await reader.readexactly(domain_len)
            elif address_type == 4:
                addr_data = await reader.readexactly(16)
            else:
                writer.close()
                return
                
            port_data = await reader.readexactly(2)

            tor_reader, tor_writer = await asyncio.open_connection("127.0.0.1", tor_port)
            
            tor_writer.write(b"\x05\x01\x02")
            await tor_writer.drain()
            tor_greeting_resp = await tor_reader.readexactly(2)
            if tor_greeting_resp[1] != 2:
                writer.close()
                return
                
            u, p = username.encode(), password.encode()
            auth_req = struct.pack("!BB", 1, len(u)) + u + struct.pack("!B", len(p)) + p
            tor_writer.write(auth_req)
            await tor_writer.drain()
            
            auth_resp = await tor_reader.readexactly(2)
            if auth_resp[1] != 0:
                writer.close()
                return
                
            tor_writer.write(req_header + addr_data + port_data)
            await tor_writer.drain()
            
            tor_resp_header = await tor_reader.readexactly(4)
            _, rep, _, tor_atyp = struct.unpack("!BBBB", tor_resp_header)
            
            if tor_atyp == 1:
                tor_addr_data = await tor_reader.readexactly(4)
            elif tor_atyp == 3:
                tor_dlen = (await tor_reader.readexactly(1))[0]
                tor_addr_data = struct.pack("!B", tor_dlen) + await tor_reader.readexactly(tor_dlen)
            elif tor_atyp == 4:
                tor_addr_data = await tor_reader.readexactly(16)
                
            tor_port_data = await tor_reader.readexactly(2)
            
            writer.write(tor_resp_header + tor_addr_data + tor_port_data)
            await writer.drain()
            
            if rep != 0:
                writer.close()
                tor_writer.close()
                return
                
            async def pump(r, w):
                try:
                    while True:
                        data = await r.read(32768)
                        if not data: break
                        w.write(data)
                        await w.drain()
                except (ConnectionResetError, ConnectionAbortedError, BrokenPipeError, OSError):
                    pass
                except Exception:
                    pass
                finally:
                    # NOTE: yahan await MAT karo (GeneratorExit hazard - upar dekho).
                    try:
                        if not w.is_closing():
                            w.close()
                    except Exception:
                        pass
                        
            await asyncio.gather(pump(reader, tor_writer), pump(tor_reader, writer))
        except (ConnectionResetError, ConnectionAbortedError, BrokenPipeError, OSError):
            pass
        except Exception:
            pass
        finally:
            # NOTE: yahan await MAT karo - GeneratorExit/shutdown ke time await
            # karne se "RuntimeError: coroutine ignored GeneratorExit" aata hai.
            # close() sync hai aur kaafi hai; socket OS reclaim kar lega.
            try:
                if not writer.is_closing():
                    writer.close()
            except Exception:
                pass

    server = await asyncio.start_server(handle_client, '127.0.0.1', 0)
    port = server.sockets[0].getsockname()[1]
    return server, port

# ── Circuit speed gate: "ek dam slow ho gya" ka permanent fix ─────────────────
# Har account se PEHLE circuit ko www.instagram.com:443 tak probe karo.
# Slow circuit (>CIRCUIT_MAX_S) mile to turant naya auth = naya Tor circuit.
# Dheeme circuit par bhari browser kholne se achha hai 10-20s me tez
# circuit dhoondh lena — yehi flush ke baad tez chalne ka asli raaz tha
# (fresh Tor = fresh tez circuits), ab har account par wahi milega.
CIRCUIT_MAX_S = 5   # seconds: isse slow circuit reject (v7.2: 12 -> 5)
CIRCUIT_TRIES = 4    # ek account ke liye max kitne circuits try kare

async def _circuit_connect_time(local_port, timeout=12):
    """Local proxy se www.instagram.com:443 tak SOCKS CONNECT me kitne sec lage.
    Fail/timeout par inf — yehi slow/dead circuit ki pehchan hai."""
    import time as _t
    t0 = _t.monotonic()
    try:
        reader, writer = await asyncio.wait_for(
            asyncio.open_connection("127.0.0.1", local_port), timeout=timeout)
        try:
            writer.write(b"\x05\x01\x00"); await writer.drain()
            if await asyncio.wait_for(reader.readexactly(2), timeout=timeout) != b"\x05\x00":
                return float("inf")
            host = b"www.instagram.com"
            writer.write(b"\x05\x01\x00\x03" + bytes([len(host)]) + host + struct.pack("!H", 443))
            await writer.drain()
            rep = await asyncio.wait_for(reader.readexactly(4), timeout=timeout)
            if rep[1] != 0:
                return float("inf")
            atyp = rep[3]
            if atyp == 1:
                await asyncio.wait_for(reader.readexactly(6), timeout=timeout)
            elif atyp == 3:
                ln = (await asyncio.wait_for(reader.readexactly(1), timeout=timeout))[0]
                await asyncio.wait_for(reader.readexactly(ln + 2), timeout=timeout)
            elif atyp == 4:
                await asyncio.wait_for(reader.readexactly(18), timeout=timeout)
            else:
                return float("inf")
            return _t.monotonic() - t0
        finally:
            writer.close()
    except Exception:
        return float("inf")

# ── IP dedupe: ek hi exit IP baar-baar na mile ───────────────────────────────
# Circuit milne ke baad account se PEHLE asal exit IP check hoti hai.
# Local window (is process ke last 100 IP) + Redis global (saare workers,
# 10 min TTL) — IP repeat mili to circuit reject, naya circuit.
_RECENT_IP_ORDER = []
_RECENT_IP_SET = set()
_RECENT_IP_MAX = 100
_RECENT_IP_LOCK = None

def _ip_lock():
    global _RECENT_IP_LOCK
    if _RECENT_IP_LOCK is None:
        _RECENT_IP_LOCK = asyncio.Lock()
    return _RECENT_IP_LOCK

async def _ip_seen_and_mark(ip):
    """True = ip recent window me pehle se hai (duplicate). Nahi hai to mark karke False."""
    async with _ip_lock():
        if ip in _RECENT_IP_SET:
            return True
        _RECENT_IP_SET.add(ip)
        _RECENT_IP_ORDER.append(ip)
        while len(_RECENT_IP_ORDER) > _RECENT_IP_MAX:
            _RECENT_IP_SET.discard(_RECENT_IP_ORDER.pop(0))
    try:
        ok = _r().set("recent_ip:" + ip, WORKER_ID, nx=True, ex=600)
        if not ok:
            return True
    except Exception:
        pass
    return False

async def _circuit_exit_ip(local_port, timeout=10):
    """Local proxy se bahar ki asal exit (IP, country). Fail par (None, None) (kaam rukega nahi)."""
    import requests as _rq
    px = {"http": f"socks5h://127.0.0.1:{local_port}", "https": f"socks5h://127.0.0.1:{local_port}"}
    try:
        resp = await asyncio.to_thread(_rq.get, "http://ip-api.com/json/", proxies=px, timeout=timeout)
        d = resp.json()
        if d.get("status") == "success" and d.get("query"):
            return d["query"], d.get("country")
    except Exception:
        pass
    try:
        resp = await asyncio.to_thread(_rq.get, "https://api.ipify.org", proxies=px, timeout=timeout)
        ip = (resp.text or "").strip()
        if ip and len(ip) <= 45 and all(c in "0123456789abcdefABCDEF:." for c in ip):
            return ip, None
    except Exception:
        pass
    return None, None

